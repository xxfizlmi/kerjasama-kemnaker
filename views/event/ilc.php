     * ============================================================
     * CURRENCY CALCULATOR
     * ============================================================
     */

    const idrInput = document.getElementById('ilcIdrInput');

    const chfResult = document.getElementById('ilcChfResult');
    const eurResult = document.getElementById('ilcEurResult');
    const usdResult = document.getElementById('ilcUsdResult');

    /*
     * Reference rates from event specification.
     */
    const CHF_RATE = 21739;
    const EUR_RATE = 20408;
    const USD_RATE = 17544;

    function updateCurrencyResult() {

        if (!idrInput) {
            return;
        }

        const idr = parseFloat(idrInput.value) || 0;

        const chf = idr / CHF_RATE;
