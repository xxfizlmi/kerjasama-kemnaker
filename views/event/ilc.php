     * ============================================================
     */

    const eventTabs = document.querySelectorAll('.ilc-event-tab');
    const eventContents = document.querySelectorAll('.ilc-event-tab-content');

    eventTabs.forEach(function (tab) {

        tab.addEventListener('click', function () {

            const target = tab.getAttribute('data-event-tab');

            eventTabs.forEach(function (item) {
                item.classList.remove('active');
            });

            eventContents.forEach(function (content) {
                content.classList.remove('active');
            });

            tab.classList.add('active');

            const targetContent = document.querySelector(
                '[data-event-content="' + target + '"]'
            );

            if (targetContent) {
                targetContent.classList.add('active');
            }

        });

    });


    /*
     * ============================================================
     * UTILITY TABS
     * ============================================================
     */

    const utilityTabs = document.querySelectorAll('.ilc-utility-tab');
    const utilityContents = document.querySelectorAll('.ilc-utility-content');

    utilityTabs.forEach(function (tab) {

        tab.addEventListener('click', function () {

            const target = tab.getAttribute('data-utility-tab');

            utilityTabs.forEach(function (item) {
                item.classList.remove('active');
            });

